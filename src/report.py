"""Builds the markdown insights report - the document an analyst hands to
product and operations teams.
"""

import os

REPORT_PATH = "output/insights_report.md"


def _pct(x):
    return f"{x:.0%}"


def _transcript_lines(order, max_turns=6):
    """Render the first few turns of a transcript as a quote block."""
    lines = [f"> **{order['order_id']}** ({order['store_name']}, day {order['day']}, "
             f"{order['day_of_week']} {order['hour']}:00) - {order['outcome']}, "
             f"MBT {order['menu_board_time_sec']}s"]
    for turn in order["transcript"][:max_turns]:
        speaker = "AI" if turn["speaker"] == "ai" else "Guest"
        lines.append(f"> {speaker}: {turn['text']}")
    return "\n".join(lines) + "\n"


def write_report(df, kpis, store_stats, region_stats, peak_stats, issue_counts,
                 friction, hourly, corr, phrases_abandoned, anomalies, extreme,
                 extreme_bounds, upsell):
    """Write the full insights report to REPORT_PATH."""
    q1, q3, iqr = extreme_bounds
    store_rows = "\n".join(
        f"| {idx} ({row['store_name']}) | {_pct(row['nir'])} | {row['mbt']:.0f} | "
        f"{_pct(row['asr'])} | {_pct(row['upsell'])} | {row['issues']:.2f} | {int(row['orders'])} |"
        for idx, row in store_stats.iterrows())
    region_rows = "\n".join(
        f"| {idx} | {_pct(row['nir'])} | {row['mbt']:.0f} | {_pct(row['upsell'])} | {row['issues']:.2f} |"
        for idx, row in region_stats.iterrows())
    peak_rows = "\n".join(
        f"| {'Peak hours' if idx else 'Off-peak'} | {_pct(row['nir'])} | {row['mbt']:.0f} | "
        f"{_pct(row['asr'])} | {row['issues']:.2f} |"
        for idx, row in peak_stats.iterrows())
    issue_rows = "\n".join(f"| {issue} | {count} |" for issue, count in issue_counts.items())
    friction_rows = "\n".join(
        f"| Turn {idx} | {count} |" for idx, count in friction.head(6).items())
    phrase_rows = "\n".join(f"| {word} | {count} |" for word, count in phrases_abandoned.items())
    anomaly_rows = "\n".join(f"| {idx} | {_pct(store_stats.loc[idx, 'nir'])} |"
                             for idx in anomalies.index)
    extreme_rows = "\n\n".join(_transcript_lines(o) for _, o in extreme.iterrows())

    findings = [
        f"Correlation between hourly Menu Board Time and NIR: **{corr:+.2f}** "
        "(negative = slower boards mean less automation).",
        f"Top issue type: **{issue_counts.index[0]}** ({issue_counts.iloc[0]} orders) - "
        "the highest-impact thing to fix.",
        "Friction is tied to item-ordering turns (2, 4, 6...): the AI most often "
        "mishears or mis-maps items right as the guest states them.",
    ]
    if not anomalies.empty:
        findings.append(f"- **{len(anomalies)} store(s) underperform**: "
                        f"{', '.join(anomalies.index)} - investigate site noise and ASR tuning.")

    recommendations = [
        "1. **Retrain on the top issue type first** - it affects the most orders.",
        "2. **Tune the noisy store(s)** - raise ASR thresholds / add noise filtering "
        "where NIR is far below average.",
        "3. **Guard the first few turns** - most friction happens while the guest "
        "states their first items; slow down and re-confirm there.",
        "4. **Use rush-hour escalation** - hand long orders to staff sooner during "
        "peak hours instead of looping the AI.",
        "5. **Keep the upsell playbook** - it adds real revenue; tune prompts at "
        "stores with below-average attach.",
    ]

    lines = [
        "# Drive-Thru Voice AI - Insights Report",
        "",
        f"_Generated by `run_analysis.py` on {len(df)} synthetic orders (30 days)_",
        "",
        "## Executive summary",
        "",
        f"The AI completes **{_pct(kpis['nir'])}** of orders with zero staff help "
        f"(NIR) and automates **{_pct(kpis['ar'])}** end-to-end. Average Menu Board "
        f"Time is **{kpis['mbt']:.0f}s**. The strongest signal in the data is the "
        f"**{corr:+.2f} correlation** between Menu Board Time and NIR: when orders "
        "take longer, the AI needs help more often. The most common failure is "
        f"**{issue_counts.index[0]}**, and friction is tied to the turns where "
        "guests state their items.",
        "",
        "## 1. Headline KPIs",
        "",
        "| KPI | Value |",
        "| --- | --- |",
        f"| Orders analysed | {kpis['total_orders']} |",
        f"| Non-Intervention Rate (NIR) | {_pct(kpis['nir'])} |",
        f"| Automation Rate (AR) | {_pct(kpis['ar'])} |",
        f"| AI Efficiency (zero-correction completions) | {_pct(kpis['ai_efficiency'])} |",
        f"| Average Menu Board Time (MBT) | {kpis['mbt']:.0f} sec |",
        f"| Average AI reply latency | {kpis['latency']:.0f} ms |",
        f"| Average ASR confidence | {_pct(kpis['asr'])} |",
        f"| Upsell attach rate (when attempted) | {_pct(kpis['upsell_attach'])} |",
        f"| Abandonment rate | {_pct(kpis['abandonment'])} |",
        f"| Average guest sentiment | {kpis['sentiment']:+.2f} |",
        f"| Average ticket | ${kpis['avg_ticket']:.2f} |",
        "",
        "## 2. Performance by store",
        "",
        "| Store | NIR | MBT (sec) | ASR | Upsell attach | Avg issues | Orders |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        store_rows,
        "",
        "## 3. Performance by region",
        "",
        "| Region | NIR | MBT (sec) | Upsell attach | Avg issues |",
        "| --- | --- | --- | --- | --- |",
        region_rows,
        "",
        "## 4. Peak hours vs off-peak",
        "",
        "| Period | NIR | MBT (sec) | ASR | Avg issues |",
        "| --- | --- | --- | --- | --- |",
        peak_rows,
        "",
        "## 5. Recurring issue types",
        "",
        "| Issue type | Orders affected |",
        "| --- | --- |",
        issue_rows,
        "",
        "## 6. Friction map (where conversations break)",
        "",
        "| Turn number | Repeats / corrections |",
        "| --- | --- |",
        friction_rows,
        "",
        "## 7. Guest phrases in abandoned orders",
        "",
        "| Word | Count |",
        "| --- | --- |",
        phrase_rows,
        "",
        "## 8. Key findings",
        "",
        *[f"- {f}" for f in findings],
        "",
        "## 9. Anomalies",
        "",
        "**Underperforming stores** (NIR more than 1 std below average):",
        "",
        "| Store | NIR |",
        "| --- | --- |",
        anomaly_rows,
        "",
        f"**Most extreme orders** (MBT above Q3 + 1.5*IQR = {q3 + 1.5 * iqr:.0f}s):",
        "",
        extreme_rows,
        "",
        "## 10. Upsell revenue impact",
        "",
        f"Over the 30 days sampled, the AI attempted {upsell['attempts']} upsells, "
        f"**{upsell['accepted']} were accepted** ({_pct(upsell['attach'])} attach), "
        f"adding **${upsell['total_uplift']:.2f}** of revenue "
        f"(avg ${upsell['avg_uplift']:.2f} per accepted order).",
        "",
        "## 11. Recommendations",
        "",
        *recommendations,
        "",
        "## 12. Charts",
        "",
        "![KPI overview](charts/kpi_overview.png)",
        "",
        "![MBT vs NIR](charts/mbt_vs_nir.png)",
        "",
        "![MBT by hour](charts/mbt_by_hour.png)",
        "",
        "![ASR by hour](charts/asr_by_hour.png)",
        "",
        "![Issue types](charts/issue_types.png)",
        "",
        "![Friction positions](charts/friction_positions.png)",
        "",
        "![NIR by store](charts/nir_by_store.png)",
        "",
        "![Upsell by store](charts/upsell_by_store.png)",
        "",
        "![Daily trend](charts/daily_trend.png)",
        "",
    ]

    os.makedirs(os.path.dirname(REPORT_PATH), exist_ok=True)
    with open(REPORT_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"Report written to {REPORT_PATH}")
